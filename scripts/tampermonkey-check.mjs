import { chromium } from 'playwright';
import path from 'node:path';
import { mkdir,mkdtemp,writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const extension=process.env.TAMPERMONKEY_PATH;
if(!extension)throw Error('Set TAMPERMONKEY_PATH to the official installed extension code directory; never use an existing browser profile.');
await mkdir('output',{recursive:true});
const profile=await mkdtemp(path.resolve('output/tampermonkey-test-'));
const context=await chromium.launchPersistentContext(profile,{...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{channel:'chromium'}),headless:true,args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`],viewport:{width:1280,height:1000}});
try{
  const worker=context.serviceWorkers()[0]||await context.waitForEvent('serviceworker',{timeout:20000});
  const id=new URL(worker.url()).host;
  const page=await context.newPage();
  await page.goto('chrome://extensions/');
  await page.getByRole('button',{name:'详情',exact:true}).click();
  const permission=page.getByRole('button',{name:/^允许运行用户脚本/});
  if(await permission.getAttribute('aria-pressed')!=='true')await permission.click();
  await page.goto(`chrome-extension://${id}/options.html#nav=utils`);
  await page.waitForTimeout(1200);
  const chooserPromise=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'Choose File',exact:true}).click();
  await (await chooserPromise).setFiles(path.resolve('dist/cozy-read-aloud.user.js'));
  await page.waitForTimeout(2000);
  const installer=context.pages().find(p=>p.url().includes('/ask.html'));
  if(!installer)throw Error('Tampermonkey installation confirmation did not open.');
  await installer.getByRole('button',{name:/^(安装|重新安装)$/}).click();
  await page.waitForTimeout(1500);
  const sample=await context.newPage();
  const base='http://cozy-public-reading.test/';
  await sample.route(base+'article.html',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="en"><title>Public reading sample</title><main><article><h1>A quiet morning</h1><p>The sun rises above the trees. A quiet path follows the river. This public sample checks a browser reading tool.</p><p>A small garden welcomes visitors. They sit beside the flowers and enjoy a peaceful morning.</p></article></main></html>'}));
  await sample.goto(base+'article.html');
  assert.equal(await sample.locator('script[src]').count(),0);
  await sample.getByRole('button',{name:'打开 Cozy 朗读',exact:true}).click({timeout:20000});
  const frame=await (await sample.locator('iframe').elementHandle()).contentFrame();
  await frame.locator('.prose').waitFor();
  assert.match(await frame.locator('.prose').innerText(),/sun rises/);
  await frame.getByRole('button',{name:'语音设置',exact:true}).click();
  await frame.locator('#engine').selectOption('mimo');
  assert.equal(await frame.locator('#mimo-voice option').count(),8);
  await sample.screenshot({path:'output/tampermonkey-installed.png'});
  await frame.getByRole('button',{name:'关闭并停止',exact:true}).click();
  await sample.getByRole('button',{name:'打开 Cozy 朗读',exact:true}).waitFor();
  await writeFile('output/tampermonkey-check.json',JSON.stringify({passed:true,extension:'Tampermonkey 5.5.1',browser:context.browser()?.version(),installedThroughUtilities:true,injectionByManager:true,webExtraction:true,mimoOptions:8,paidRequests:0,realSpeech:false},null,2));
  console.log('Real Tampermonkey installation passed: script injection, webpage extraction, MiMo settings and close.');
  await writeFile('output/tampermonkey-extension.json',JSON.stringify({id,worker:worker.url()},null,2));
}finally{await context.close();}
