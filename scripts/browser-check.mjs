import { chromium } from 'playwright';
import { PDFDocument, StandardFonts } from 'pdf-lib';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.BASE_URL||'http://127.0.0.1:5199/';
const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||'msedge'});
await mkdir('output',{recursive:true});
const errors=[], requests=[];
try {
  const context=await browser.newContext({viewport:{width:1360,height:1000}});
  await context.route('**/*',route=>{
    const url=route.request().url();
    if(url.startsWith(base)||url.startsWith('blob:')||url.startsWith('data:')) return route.continue();
    requests.push(url);return route.abort();
  });
  await context.addInitScript(()=>{
    const local={name:'Public local test voice',voiceURI:'local-test',lang:'en-US',localService:true};
    const remote={name:'Public remote test voice',voiceURI:'remote-test',lang:'en-US',localService:false};
    window.__spoken=[];
    Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[local,remote],addEventListener(){},cancel(){},pause(){},resume(){},speak(u){window.__spoken.push(u);}}});
    Object.defineProperty(window,'SpeechSynthesisUtterance',{value:class{constructor(text){this.text=text;}}});
  });
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.evaluate(()=>{const p=document.querySelector('article p'); const hidden=document.createElement('span');hidden.style.display='none';hidden.textContent='HIDDEN_PRIVATE_SENTINEL';p.append(hidden);const input=document.createElement('input');input.value='INPUT_PRIVATE_SENTINEL';p.append(input);});
  await page.getByRole('button',{name:'打开 Cozy 朗读',exact:true}).click();
  const frame=await (await page.locator('iframe[title="Cozy Read Aloud 阅读面板"]').elementHandle()).contentFrame();
  await frame.locator('.prose').waitFor();
  assert.match(await frame.locator('.prose').innerText(),/清晨的公园/);
  assert.doesNotMatch(await frame.locator('.prose').innerText(),/PRIVATE_SENTINEL/);
  await frame.getByRole('button',{name:'播放',exact:true}).click();
  await frame.getByRole('button',{name:'暂停',exact:true}).waitFor();
  const count=await frame.evaluate(()=>__spoken.length);
  await frame.getByRole('button',{name:'暂停',exact:true}).click();
  await frame.getByRole('button',{name:'继续',exact:true}).click();
  assert.equal(await frame.evaluate(()=>__spoken.length),count);
  await frame.getByRole('button',{name:'下一段',exact:true}).click();
  await frame.evaluate(()=>__spoken[0].onend());
  assert.equal(await frame.evaluate(()=>__spoken.length),count+1);
  await frame.getByRole('button',{name:'停止',exact:true}).click();
  await frame.getByRole('button',{name:'语音设置',exact:true}).click();
  assert.equal(await frame.locator('#voice option').count(),2);
  await frame.locator('#remote-voices').check();assert.equal(await frame.locator('#voice option').count(),3);
  await frame.locator('#remote-voices').uncheck();
  await frame.getByRole('button',{name:'语音设置',exact:true}).click();
  await frame.getByRole('button',{name:'关闭并停止',exact:true}).click();
  await page.evaluate(()=>{const node=document.querySelector('article p').firstChild;const range=document.createRange();range.setStart(node,0);range.setEnd(node,10);getSelection().removeAllRanges();getSelection().addRange(range);});
  await page.getByRole('button',{name:'打开 Cozy 朗读',exact:true}).click();
  await frame.waitForFunction(()=>document.querySelector('.prose')?.textContent.length===10);
  await frame.getByRole('button',{name:'从选区继续',exact:true}).click();
  await frame.waitForFunction(()=>document.querySelector('.prose')?.textContent.length>150);
  assert.ok((await frame.locator('.prose').innerText()).startsWith('清晨的公园'));
  await frame.getByRole('button',{name:'网页正文',exact:true}).click();
  await frame.waitForFunction(()=>document.querySelector('.prose')?.textContent.length>150);
  await frame.getByRole('button',{name:'展开阅读面板',exact:true}).click();
  await frame.waitForFunction(()=>innerWidth>800);
  await frame.waitForTimeout(200);
  await page.screenshot({path:'output/web-desktop.png'});
  const pdf=await PDFDocument.create(),font=await pdf.embedFont(StandardFonts.Helvetica);
  for(let n=1;n<=2;n++) {
    const p=pdf.addPage([595,842]);
    p.drawText(`Public reading sample page ${n}`,{x:50,y:760,size:18,font});
    p.drawText(`A quiet morning begins beside the river.`,{x:50,y:710,size:12,font});
    p.drawText(`This public sentence belongs to page ${n}.`,{x:50,y:680,size:12,font});
    p.drawText(`The next sentence is ready to read aloud.`,{x:50,y:650,size:12,font});
  }
  const buffer=Buffer.from(await pdf.save());
  await frame.locator('#pdf-file').setInputFiles({name:'public-reading.pdf',mimeType:'application/pdf',buffer});
  await frame.locator('.textLayer [data-pdf-item]').first().waitFor({timeout:45000});
  assert.equal(await frame.locator('.pdf-page').count(),2);
  const pixels = await frame.locator('canvas').first().evaluate(canvas=>{const data=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;let dark=0;for(let i=0;i<data.length;i+=4)if(data[i]<100&&data[i+1]<100&&data[i+2]<100&&data[i+3]>0)dark++;return dark;});
  assert.ok(pixels>100,'PDF canvas must contain rendered text');
  assert.equal(await page.evaluate(()=>{try{return !!document.querySelector('[data-cozy-host]').shadowRoot.querySelector('iframe').contentDocument?.body;}catch{return false;}}),false);
  await frame.getByRole('button',{name:'播放',exact:true}).click();
  await frame.getByRole('button',{name:'暂停',exact:true}).waitFor();
  await frame.getByRole('button',{name:'停止',exact:true}).click();
  await frame.getByRole('button',{name:'放大 PDF',exact:true}).click();
  assert.equal(await frame.locator('#zoom-label').innerText(),'125%');
  await frame.getByRole('button',{name:'适合宽度',exact:true}).click();
  await frame.locator('.textLayer [data-pdf-item]').first().waitFor();
  await frame.locator('.textLayer [data-pdf-item]').first().scrollIntoViewIfNeeded();
  await frame.evaluate(()=>{const span=[...document.querySelectorAll('.textLayer [data-pdf-item]')].find(s=>s.textContent.includes('quiet morning'));const range=document.createRange();range.selectNodeContents(span);getSelection().removeAllRanges();getSelection().addRange(range);document.dispatchEvent(new Event('selectionchange'));});
  await frame.locator('#scope').selectOption('selected');
  await frame.getByRole('button',{name:'播放',exact:true}).click();
  await frame.getByRole('button',{name:'暂停',exact:true}).waitFor();
  assert.match(await frame.evaluate(()=>__spoken.at(-1).text),/quiet morning/);
  await page.screenshot({path:'output/pdf-desktop.png'});
  await frame.getByRole('button',{name:'停止',exact:true}).click();
  await frame.locator('#scope').selectOption('from');
  await frame.getByRole('button',{name:'播放',exact:true}).click();
  await frame.getByRole('button',{name:'暂停',exact:true}).waitFor();
  assert.ok(Number(await frame.locator('#progress').getAttribute('max'))>1);
  await frame.getByRole('button',{name:'停止',exact:true}).click();
  await frame.getByRole('button',{name:'文档大纲',exact:true}).click();
  await frame.locator('#outline button').last().click();
  const layouts=[];
  for(const width of [768,390,320]) {
    await page.setViewportSize({width,height:844});
    await frame.waitForTimeout(180);
    const box=await page.locator('iframe[title="Cozy Read Aloud 阅读面板"]').boundingBox();
    assert.ok(box.x>=0&&box.x+box.width<=width);
    const overflow=await frame.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    assert.equal(overflow,false);
    await page.screenshot({path:`output/pdf-${width}.png`});layouts.push({width,overflow});
  }
  await frame.locator('#pdf-file').setInputFiles({name:'invalid-public.pdf',mimeType:'application/pdf',buffer:Buffer.from('Not a PDF')});
  await frame.waitForFunction(()=>document.getElementById('notice').textContent.includes('Invalid PDF'));
  assert.equal(await frame.locator('#play').isDisabled(),false);
  assert.equal(await frame.locator('.pdf-page').count(),0);
  await frame.getByRole('button',{name:'关闭并停止',exact:true}).click();
  await page.getByRole('button',{name:'打开 Cozy 朗读',exact:true}).waitFor();
  assert.deepEqual(requests,[]);assert.deepEqual(errors,[]);
  await writeFile('output/browser-check.json',JSON.stringify({passed:true,pdfSelection:true,pdfContinuation:true,pdfIsolation:true,pdfCanvasNonblank:true,pdfZoom:true,invalidPdfRecovery:true,webContinuation:true,hiddenTextExcluded:true,pauseResume:true,staleCallbacksRejected:true,localVoiceDefault:true,layouts,externalRequests:requests,errors,realSpeech:false,extensionManagerInstalled:false},null,2)+'\n');
  console.log('Browser checks passed: public page/PDF, selection, isolation, playback and responsive layouts. No external requests.');
} finally {await browser.close();}
